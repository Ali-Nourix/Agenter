async function ensureFolder(app, folder) {
  const clean = folder.split("/").filter(Boolean);
  let current = "";
  for (const part of clean) {
    current = current ? `${current}/${part}` : part;
    const found = app.vault.getAbstractFileByPath(current);
    if (found && !(found instanceof import_obsidian4.TFolder)) throw new Error(`Not a folder: ${current}`);
    if (!found) {
      try {
        await app.vault.createFolder(current);
      } catch (error) {
        const afterCreate = app.vault.getAbstractFileByPath(current);
        const message = error instanceof Error ? error.message : String(error);
        if (!(afterCreate instanceof import_obsidian4.TFolder) && !/already exists/i.test(message)) throw error;
      }
    }
  }
}
